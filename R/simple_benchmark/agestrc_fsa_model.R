#' Deterministic numbers at age on the log scale (plain R, no AD)
#'
#' Used by the simulator and to start auxiliary random effects at values that
#' are consistent with the starting fixed effects.
#'
#' @param ln_Ninit Log numbers at age in year 1 (length n_a)
#' @param lnN1 Log recruitment in years 2..n_t (length n_t - 1)
#' @param Z_at Total mortality, n_a x n_t
#' @param plus_group Oldest age is a plus group
det_lnN <- function(ln_Ninit, lnN1, Z_at, plus_group = TRUE) {
  n_a <- nrow(Z_at); n_t <- ncol(Z_at)
  ln_N <- matrix(0, n_a, n_t)
  ln_N[, 1] <- ln_Ninit
  ln_N[1, 2:n_t] <- lnN1
  for (t in 2:n_t) {
    ln_N[2:n_a, t] <- ln_N[1:(n_a - 1), t - 1] - Z_at[1:(n_a - 1), t - 1]
    if (plus_group)
      ln_N[n_a, t] <- log(exp(ln_N[n_a, t]) + exp(ln_N[n_a, t - 1] - Z_at[n_a, t - 1]))
  }
  ln_N
}

#' Simulate one data set from the aligned model
#'
#' Data are generated by the estimation model itself (separable F, iid
#' lognormal observation errors), as in the simulation component.
#'
#' @param truth List from agestrc_fsa_truth(): M_a, logF_a, logF_t, logQ_a,
#'   srv_ages, survey_time, sigmaC, sigmaI, logR0, sigmaR, phi, theta, ln_Ninit
#' @param n_t Number of years; the fitted F-by-year series is recycled
#' @param rec_proc "ar1" (sigmaR is the marginal SD) or "ma1" (innovation SD)
#' @param plus_group Oldest age is a plus group
#' @param seed Simulation seed
sim_agestrc_fsa <- function(truth, n_t, rec_proc = c("ar1", "ma1"),
                            plus_group = TRUE, seed = 1) {
  rec_proc <- match.arg(rec_proc)
  set.seed(seed)
  n_a <- length(truth$M_a)

  logF_t <- rep_len(truth$logF_t, n_t)
  F_at <- exp(outer(truth$logF_a, logF_t, "+"))
  Z_at <- F_at + truth$M_a

  # recruitment in years 2..n_t; year 1 is ln_Ninit[1]
  z <- rnorm(n_t)
  lnN1 <- numeric(n_t - 1)
  if (rec_proc == "ar1") {
    prev <- truth$ln_Ninit[1]
    for (t in seq_len(n_t - 1)) {
      lnN1[t] <- truth$phi * prev + truth$logR0 * (1 - truth$phi) +
        truth$sigmaR * sqrt(1 - truth$phi^2) * z[t + 1]
      prev <- lnN1[t]
    }
  } else {
    eps <- truth$sigmaR * z
    for (t in seq_len(n_t - 1))
      lnN1[t] <- truth$logR0 + eps[t + 1] + truth$theta * eps[t]
  }

  ln_N <- det_lnN(truth$ln_Ninit, lnN1, Z_at, plus_group)

  lC_at_true <- log(F_at / Z_at * (1 - exp(-Z_at))) + ln_N
  lI_at_true <- truth$logQ_a - Z_at[truth$srv_ages, ] * truth$survey_time +
    ln_N[truth$srv_ages, ]
  lC_at <- lC_at_true + truth$sigmaC * matrix(rnorm(n_a * n_t), n_a, n_t)
  lI_at <- lI_at_true + truth$sigmaI *
    matrix(rnorm(length(truth$srv_ages) * n_t), length(truth$srv_ages), n_t)

  list(n_a = n_a, n_t = n_t, lC_at = lC_at, lI_at = lI_at, lN = ln_N,
       F_at = F_at, Z_at = Z_at, plus_group = plus_group, rec_proc = rec_proc,
       seed = seed)
}

#' Joint negative log likelihood of the aligned age-structured model
#'
#' @param data List: n_a, n_t, ln_C (n_a x n_t), ln_I (survey ages x n_t; NA
#'   where there is no survey), M_a, srv_ages, survey_time, plus
#'   (none|naive|logspace), rec_proc (ar1|ma1), rec_re (state|innovation),
#'   surv (deterministic|aux_plus|aux_all|state), tiny, sparse_lse, sd_prior
#' @param pars Parameter list; only what the configuration uses need be present
jnll_agestrc_fsa <- function(data, pars) {

  "[<-" <- RTMB::ADoverload("[<-")
  "c" <- RTMB::ADoverload("c")

  RTMB::getAll(data, pars)
  stopifnot(rec_proc %in% c("ma1", "ar1"),
            rec_re %in% c("state", "innovation"),
            plus %in% c("none", "naive", "logspace"),
            surv %in% c("deterministic", "aux_plus", "aux_all", "state"))

  jnll <- 0

  sigmaR <- exp(logsigmaR)
  sigmaC <- exp(logsigmaC)
  sigmaI <- exp(logsigmaI)
  if (surv == "state") sigmaS <- exp(logsigmaS)                  # estimated
  if (surv == "aux_all" || surv == "aux_plus") sigmaS <- tiny    # pinned

  # N(0, 1) priors on the log SDs, as in the simulation component
  if (sd_prior) {
    jnll <- jnll - RTMB::dnorm(logsigmaC, 0, 1, TRUE)
    jnll <- jnll - RTMB::dnorm(logsigmaI, 0, 1, TRUE)
    jnll <- jnll - RTMB::dnorm(logsigmaR, 0, 1, TRUE)
    if (surv == "state") jnll <- jnll - RTMB::dnorm(logsigmaS, 0, 1, TRUE)
  }

  # separable fishing mortality, natural mortality at age as data
  ln_Fat <- logF_a + rep(logF_t, each = n_a)
  dim(ln_Fat) <- c(n_a, n_t)
  F_at <- exp(ln_Fat)
  Z_at <- F_at + M_a

  ## recruitment in years 2..n_t; year 1 is the fixed effect ln_Ninit[1] --------
  lnN1 <- numeric(n_t - 1)

  # AR(1), state: log recruitment is the latent; sigmaR is the marginal sd
  if (rec_proc == "ar1" && rec_re == "state") {
    phi <- 2 * plogis(trans_phiR) - 1
    lnN1 <- ln_R
    jnll <- jnll - RTMB::dautoreg(c(ln_Ninit[1], ln_R), mu = logR0, phi = phi,
                                  scale = sigmaR, log = TRUE)
  }

  # AR(1), innovation: standard-normal innovations drive the recursion
  if (rec_proc == "ar1" && rec_re == "innovation") {
    phi <- 2 * plogis(trans_phiR) - 1
    jnll <- jnll - sum(RTMB::dnorm(epsR, 0, 1, TRUE))
    jnll <- jnll - RTMB::dnorm(ln_Ninit[1], logR0, sigmaR, TRUE)
    lnN1[1] <- phi * ln_Ninit[1] + logR0 * (1 - phi) + sigmaR * sqrt(1 - phi^2) * epsR[1]
    for (t in 2:(n_t - 1))
      lnN1[t] <- phi * lnN1[t - 1] + logR0 * (1 - phi) + sigmaR * sqrt(1 - phi^2) * epsR[t]
  }

  # MA(1), innovation: innovations are the latent (length n_t)
  if (rec_proc == "ma1" && rec_re == "innovation") {
    theta <- 2 * plogis(trans_thetaR) - 1
    jnll <- jnll - sum(RTMB::dnorm(epsR, 0, sigmaR, TRUE))
    for (t in 1:(n_t - 1)) lnN1[t] <- logR0 + epsR[t + 1] + theta * epsR[t]
  }

  # MA(1), state: recruitment deviations from the mean are the latent (length
  # n_t); inverting the filter makes each innovation read every earlier state
  if (rec_proc == "ma1" && rec_re == "state") {
    theta <- 2 * plogis(trans_thetaR) - 1
    e <- numeric(n_t)
    e[1] <- ln_R[1]
    for (t in 2:n_t) e[t] <- ln_R[t] - theta * e[t - 1]
    jnll <- jnll - sum(RTMB::dnorm(e, 0, sigmaR, TRUE))
    lnN1 <- ln_R[2:n_t] + logR0
  }

  ## numbers at age -------------------------------------------------------------
  ln_N <- array(0, dim = c(n_a, n_t))
  ln_N[, 1] <- ln_Ninit
  ln_N[1, 2:n_t] <- lnN1
  if (surv == "state" || surv == "aux_all") ln_N[2:n_a, 2:n_t] <- ln_N2 # ages 2+ as latents
  if (surv == "aux_plus") ln_N[n_a, 2:n_t] <- aux_t                     # plus group only

  ln_Npred <- array(0, dim = c(n_a, n_t))
  for (t in 2:n_t) {

    # not the plus group
    for (a in 2:(n_a - 1)) ln_Npred[a, t] <- ln_N[a - 1, t - 1] - Z_at[a - 1, t - 1]

    # oldest age: true age (none), naive log-sum-exp, or the log-space trick
    ln_plus <- c(ln_N[n_a - 1, t - 1] - Z_at[n_a - 1, t - 1], ln_N[n_a, t - 1] - Z_at[n_a, t - 1])
    if (plus == "none") ln_Npred[n_a, t] <- ln_plus[1]
    if (plus == "naive") ln_Npred[n_a, t] <- log(sum(exp(ln_plus)))
    if (plus == "logspace") ln_Npred[n_a, t] <- logspace_sum(ln_plus, sparse_lse)

    # deterministic: the state is the prediction, needed by the next year
    if (surv == "deterministic") ln_N[2:n_a, t] <- ln_Npred[2:n_a, t]
    if (surv == "aux_plus") ln_N[2:(n_a - 1), t] <- ln_Npred[2:(n_a - 1), t]
  }

  # all ages 2+ as latents: sd estimated (state) or pinned (aux_all)
  if (surv == "state" || surv == "aux_all") {
    jnll <- jnll - sum(RTMB::dnorm(ln_N[2:n_a, 2:n_t], ln_Npred[2:n_a, 2:n_t], sigmaS, TRUE))
  }

  # plus group only as a latent, pinned
  if (surv == "aux_plus") {
    jnll <- jnll - sum(RTMB::dnorm(ln_N[n_a, 2:n_t], ln_Npred[n_a, 2:n_t], sigmaS, TRUE))
  }

  ## observations ---------------------------------------------------------------
  ln_Cpred <- log(F_at / Z_at * (1 - exp(-Z_at))) + ln_N            # Baranov
  ln_Ipred <- logQ_a - Z_at[srv_ages, ] * survey_time + ln_N[srv_ages, ]

  iC <- which(!is.na(ln_C))
  iI <- which(!is.na(ln_I))
  jnll <- jnll - sum(RTMB::dnorm(ln_C[iC], ln_Cpred[iC], sigmaC, TRUE))
  jnll <- jnll - sum(RTMB::dnorm(ln_I[iI], ln_Ipred[iI], sigmaI, TRUE))

  RTMB::REPORT(ln_N)
  RTMB::REPORT(ln_Npred)
  RTMB::REPORT(ln_Cpred)
  RTMB::REPORT(ln_Ipred)
  RTMB::REPORT(F_at)

  jnll
}
